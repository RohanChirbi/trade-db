"""tests/validate_pandas.py : recompute Q01, Q02, Q04 and Q13 in pandas and compare with the SQL results.

Both sides read the same live tables (exported with psql), so any difference is a query bug.
Usage:  python3 tests/validate_pandas.py
        PSQL="docker exec -i trading_postgres psql -U trading_admin -d trading_db" python3 tests/validate_pandas.py
Writes docs/PANDAS_CROSSCHECK.md and exits non-zero on a mismatch.
"""
import io, os, shlex, subprocess, sys
from datetime import datetime, timezone
from pathlib import Path
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
PSQL = shlex.split(os.environ.get("PSQL", f"sh {ROOT / 'scripts/psql.sh'}"))


def sql(query: str) -> pd.DataFrame:
    out = subprocess.run(PSQL + ["-X", "-q", "--csv", "-v", "ON_ERROR_STOP=1"], input=query + ";",
                         capture_output=True, text=True, check=True).stdout
    return pd.read_csv(io.StringIO(out))


def query_file(name: str) -> str:
    text = (ROOT / "sql/queries" / name).read_text()
    return "\n".join(l for l in text.splitlines() if not l.lstrip().startswith("--")).strip().rstrip(";")


def compare(name, sql_df, pd_df, keys, cols, tol=1e-3):
    m = sql_df.merge(pd_df, on=keys, how="outer", suffixes=("_sql", "_pd"), indicator=True)
    missing = int((m["_merge"] != "both").sum())
    worst = 0.0
    for c in cols:
        worst = max(worst, float(np.nanmax(np.abs(m[f"{c}_sql"].astype(float) - m[f"{c}_pd"].astype(float))) if len(m) else 0))
    ok = missing == 0 and worst <= tol
    print(f"{'PASS' if ok else 'FAIL'}  {name}: {len(m)} rows, unmatched {missing}, max abs diff {worst:.6f}")
    return dict(query=name, rows=len(m), unmatched=missing, max_diff=worst, columns=", ".join(cols), ok=ok)


quotes = sql("SELECT ticker, bid_price, ask_price FROM market_quote")
orders = sql("SELECT order_id, strategy_id, ticker, side, quantity FROM orders")
execs = sql("SELECT order_id, exec_qty, exec_price, (exec_ts AT TIME ZONE 'Asia/Kolkata')::date AS trade_date FROM execution")
risk = sql("SELECT strategy_id, trade_date, daily_pnl FROM risk_metric")
strategy = sql("SELECT strategy_id, name FROM strategy")
results = []

# Q01 spread per security
q = quotes.assign(spread=quotes.ask_price - quotes.bid_price)
q["bps"] = q.spread / ((q.ask_price + q.bid_price) / 2) * 10000
p01 = q.groupby("ticker").agg(avg_spread=("spread", "mean"), avg_spread_bps=("bps", "mean")).reset_index()
p01 = p01.assign(avg_spread=p01.avg_spread.round(4), avg_spread_bps=p01.avg_spread_bps.round(2))
results.append(compare("Q01 spread", sql(query_file("q01_spread.sql")), p01, ["ticker"], ["avg_spread", "avg_spread_bps"], tol=0.011))

# Q02 daily VWAP per security
e = execs.merge(orders[["order_id", "ticker"]], on="order_id")
e["value"] = e.exec_qty * e.exec_price
p02 = e.groupby(["ticker", "trade_date"]).agg(volume=("exec_qty", "sum"), value=("value", "sum")).reset_index()
p02["vwap"] = (p02.value / p02.volume).round(4)
results.append(compare("Q02 VWAP", sql(query_file("q02_vwap.sql")), p02[["ticker", "trade_date", "volume", "vwap"]],
                       ["ticker", "trade_date"], ["volume", "vwap"], tol=0.00011))  # 4-dp rounding: exact NUMERIC vs float

# Q04 fill ratio per strategy
filled = execs.groupby("order_id").exec_qty.sum().rename("filled")
o = orders.join(filled, on="order_id").fillna({"filled": 0})
p04 = o.groupby("strategy_id").agg(orders=("order_id", "count"), ordered_qty=("quantity", "sum"), filled_qty=("filled", "sum")).reset_index()
p04["fill_ratio"] = (p04.filled_qty / p04.ordered_qty).round(4)
results.append(compare("Q04 fill ratio", sql(query_file("q04_fill_ratio_strategy.sql")), p04,
                       ["strategy_id"], ["orders", "ordered_qty", "filled_qty", "fill_ratio"], tol=0.0001))

# Q13 cumulative P&L (running sum per strategy)
r = risk.sort_values(["strategy_id", "trade_date"]).copy()
r["cumulative_pnl"] = r.groupby("strategy_id").daily_pnl.cumsum()
results.append(compare("Q13 cumulative P&L", sql(query_file("q13_cumulative_pnl.sql")), r[["strategy_id", "trade_date", "cumulative_pnl"]],
                       ["strategy_id", "trade_date"], ["cumulative_pnl"], tol=0.01))

ok = all(x["ok"] for x in results)
lines = ["# pandas cross-check", "",
         f"Generated by `python3 tests/validate_pandas.py` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC.",
         "Each query's result is recomputed independently in pandas from the raw tables and joined on its key columns.", "",
         "| Query | Rows compared | Unmatched rows | Columns compared | Max abs difference | Result |", "|---|---|---|---|---|---|"]
lines += [f"| {x['query']} | {x['rows']} | {x['unmatched']} | {x['columns']} | {x['max_diff']:.6f} | {'PASS' if x['ok'] else '**FAIL**'} |" for x in results]
lines += ["", "Differences are rounding only: SQL rounds to 2 or 4 decimals, pandas computes in floating point."]
(ROOT / "docs/PANDAS_CROSSCHECK.md").write_text("\n".join(lines) + "\n")
sys.exit(0 if ok else 1)
